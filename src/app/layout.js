
import { Hind_Siliguri } from "next/font/google";
import "./globals.css";
import Navbar from "@/components/Navber";
import baseUrl from "@/services/baseUrl";
import { Toaster } from "react-hot-toast";
import Marquee from "@/components/Marquee";
import ProductCard from "@/components/ProductCard";
import Footer from "@/components/Footer";

const hindSiliguri = Hind_Siliguri({
  subsets: ["latin", "bengali"],
  weight: ["300", "400", "500", "600", "700"],
});

export const metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

const getCategories = async () => {
  const res = await fetch(`${baseUrl}/categories`);

  if (!res.ok) {
    throw new Error("Failed to fetch categories");
  }

  return res.json();
};

const getProducts = async () => {
  const res = await fetch(`${baseUrl}/products`);

  if (!res.ok) {
    throw new Error("Failed to fetch products");
  }

  return res.json();
};

export default async function RootLayout({ children }) {
  const categories = await getCategories();
  const products = await getProducts();

  // যেসব পণ্যের দাম বেড়েছে
  const upProducts = products.filter(
    (product) => product.priceChange > 0
  );

  // যেসব পণ্যের দাম কমেছে
  const downProducts = products.filter(
    (product) => product.priceChange < 0
  );

  return (
    <html
      lang="bn"
      data-theme="light"
      className={`${hindSiliguri.className} h-full antialiased`}
    >
      <body suppressHydrationWarning className="min-h-full flex flex-col">
        <Navbar categories={categories} />

        <div>
          <Marquee products={products} />

          {/* দাম বেড়েছে */}
          {/* <div className="w-full max-w-5xl mx-auto mt-6">
            <p className="text-2xl font-bold">
              <span className="text-red-600">▲</span> আজ দাম বেড়েছে
            </p> */}

            <div className="grid grid-cols-3 gap-4 mt-4">
              {upProducts.map((product) => (
                <ProductCard key={product.id} product={product} />
              ))}
            {/* </div> */}
          </div>

          {/* দাম কমেছে */}
        

            <div className="grid grid-cols-3 gap-4 mt-4">
              {downProducts.map((product) => (
                <ProductCard key={product.id} product={product} />
              ))}
            {/* </div> */}
          </div>
        </div>
 <Toaster position="top-right" />
        {children}
       
       
         
        <Footer/>
      </body>
    </html>
  );
}
